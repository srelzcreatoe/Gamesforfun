// Where each animatronic's head points, and where its eyes are, in every pose it can be looked at in.
// The game turns heads with two additive angles (fnar:look_yaw / fnar:look_pitch on top of the pose), so
// to look AT something it has to know what the pose already does to the head: stage poses tilt it, the
// lean at the office door bends the whole body forward. Writes packs/BP/scripts/data/head_aim.js:
//
//   HEAD_AIM[id][anim] = [yaw, pitch, right, up, forward]
//     yaw, pitch       the head's own direction in that pose, relative to the entity's facing
//                      (degrees, Minecraft convention: yaw + = to its right, pitch + = down)
//     right/up/forward the point between the eyes, from the feet (blocks, at the entity's render scale)
//
// Looping poses are averaged over the loop. Usage: node tools/entities/head_aim.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from '../node_modules/three/build/three.module.js';
import { PNG } from '../node_modules/pngjs/lib/png.js';
import { buildModel, applyAnimation } from '../render/bedrock_model.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const IDS = ['rustgrin', 'mirehop', 'noxbriar', 'purple_rat', 'cat', 'top_hat_rat', 'golden_dog'];
/** fnar:anim value -> animation name (tools/entities/build_entities.py ANIMS); only poses a head is turned in */
const ANIMS = { idle: 'idle', stand: 'idle', pose: 'pose_1', slump: 'pose_2', perform: 'perform_1', perform2: 'perform_2', peek: 'peek', lean: 'lean', wave: 'wave', bow: 'bow' };
const readJ = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const r1 = (v) => Math.round(v * 10) / 10;
const r2 = (v) => Math.round(v * 100) / 100;

/** The middle of the glowing pupils on the head's front face (model px, in the eye cube's bone). */
function eyePoint(id, geo) {
  const png = PNG.sync.read(fs.readFileSync(`${ROOT}/packs/RP/textures/entity/fnar/${id}_eyes.png`));
  for (const b of geo['minecraft:geometry'][0].bones) {
    for (const c of b.cubes ?? []) {
      const n = c.uv?.north;
      if (!n) continue;
      const [u, v] = n.uv;
      const [us, vs] = n.uv_size;
      let hit = 0, sx = 0, sy = 0;
      for (let y = Math.floor(Math.min(v, v + vs)); y < Math.ceil(Math.max(v, v + vs)); y++) {
        for (let x = Math.floor(Math.min(u, u + us)); x < Math.ceil(Math.max(u, u + us)); x++) {
          const k = (y * png.width + x) * 4;
          if (png.data[k + 3] > 200) { hit++; sx += (x + 0.5 - u) / us; sy += (y + 0.5 - v) / vs; }
        }
      }
      if (hit) return { bone: b.name, p: [c.origin[0] + c.size[0] * (1 - sx / hit), c.origin[1] + c.size[1] * (1 - sy / hit), c.origin[2]] };
    }
  }
  throw new Error(`${id}: no eye pixels on a north face`);
}

const out = {};
for (const id of IDS) {
  const geo = readJ(`${ROOT}/packs/RP/models/entity/fnar_${id}.geo.json`);
  const anims = readJ(`${ROOT}/packs/RP/animations/fnar_${id}.animation.json`).animations;
  const S = Number(readJ(`${ROOT}/packs/RP/entity/fnar_${id}.entity.json`)['minecraft:client_entity'].description.scripts.scale);
  const M = buildModel(geo, null);
  const eye = eyePoint(id, geo);
  const eb = geo['minecraft:geometry'][0].bones.find((b) => b.name === eye.bone);
  const head = M.bones.get('head');
  if (!head) throw new Error(`${id}: no head bone`);
  out[id] = {};
  for (const [key, name] of Object.entries(ANIMS)) {
    const a = anims[`animation.fnar.${id}.${name}`];
    if (!a) throw new Error(`${id}: no animation ${name}`);
    const len = a.animation_length ?? 0;
    const dir = new THREE.Vector3();
    const pos = new THREE.Vector3();
    let n = 0;
    // a bow or a wave ends on its held frame: aim from there; loops are averaged
    const times = a.loop === true && len > 0 ? Array.from({ length: Math.ceil(len / 0.1) }, (_, i) => i * 0.1) : [len];
    for (const t of times) {
      applyAnimation(M, a, t);
      M.root.updateMatrixWorld(true);
      const q = new THREE.Quaternion();
      head.node.getWorldQuaternion(q);
      dir.add(new THREE.Vector3(0, 0, -1).applyQuaternion(q));
      const ev = new THREE.Vector3(-(eye.p[0] - eb.pivot[0]) / 16, (eye.p[1] - eb.pivot[1]) / 16, (eye.p[2] - eb.pivot[2]) / 16);
      M.bones.get(eye.bone).node.localToWorld(ev);
      pos.add(ev);
      n++;
    }
    dir.normalize();
    pos.multiplyScalar(S / n);
    // the model's front is -Z, its right +X
    const yaw = (Math.atan2(dir.x, -dir.z) * 180) / Math.PI;
    const pitch = (-Math.asin(Math.max(-1, Math.min(1, dir.y))) * 180) / Math.PI;
    out[id][key] = [r1(yaw), r1(pitch), r2(pos.x), r2(pos.y), r2(-pos.z)];
  }
}

const lines = [
  '// Generated by tools/entities/head_aim.mjs from the models and animations: do not edit.',
  "// HEAD_AIM[id][fnar:anim] = [yaw, pitch, right, up, forward]: the head's own direction in that pose relative to",
  '// the entity facing (degrees; yaw + = to its right, pitch + = down) and the point between its eyes from the feet',
  '// (blocks, at render scale). mc/aim.js uses it to turn a head AT a point.',
  'export const HEAD_AIM = Object.freeze({',
  ...Object.entries(out).map(([id, o]) => `  ${id}: Object.freeze({ ${Object.entries(o).map(([k, v]) => `${k}: [${v.join(', ')}]`).join(', ')} }),`),
  '});',
  '',
];
fs.writeFileSync(`${ROOT}/packs/BP/scripts/data/head_aim.js`, lines.join('\n'));
for (const [id, o] of Object.entries(out)) console.log(id.padEnd(12), Object.entries(o).map(([k, v]) => `${k} ${v[0]}/${v[1]}`).join('  '));
