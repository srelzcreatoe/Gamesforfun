FONTS = {'small': (SMALL, SMALL_CONDENSED, 5), 'tall': (TALL, TALL_CONDENSED, 7), 'neon': (NEON, {}, 9)}
# kerning pairs: added to the 1-px spacing (-1 = letters touch at the bounding box)
KERN = {('T', 'A'): -1, ('L', 'T'): -1}
# applied only when both glyphs are condensed (tight titles): the 1-px apostrophe sits in the gap
KERN_CONDENSED = {('O', "'"): -1, ("'", 'S'): -1}


def glyph(ch, font='small', condensed=False):
    base, cond, h = FONTS[font]
    if condensed and ch in cond:
        return cond[ch]
    if ch in base:
        return base[ch]
    if font == 'tall' and ch in SMALL:  # fall back: pad the small glyph to 7 rows
        g = SMALL[ch]
        return g[:2] + [g[2]] * 1 + [g[2]] + g[2:4] + [g[4]]
    raise KeyError(f'glyph {ch!r} missing in {font}')


def render(text, font='small', condensed=False, spacing=1, cond_chars=None):
    """Returns a bool mask. cond_chars: set of chars to condense (overrides `condensed`)."""
    _, _, h = FONTS[font]
    cols = []
    prev = None
    for ch in text:
        c = condensed if cond_chars is None else (ch in cond_chars)
        g = glyph(ch, font, c)
        w = max(len(r) for r in g)
        if prev is not None and spacing:
            gap = spacing + KERN.get((prev, ch), 0)
            if c and (prev, ch) in KERN_CONDENSED:
                gap += KERN_CONDENSED[(prev, ch)]
            if gap > 0:
                cols.append(np.zeros((h, gap), bool))
        m = np.zeros((h, w), bool)
        for y, row in enumerate(g):
            for x, cc in enumerate(row):
                m[y, x] = cc == '#'
        cols.append(m)
        prev = ch
    return np.concatenate(cols, 1) if cols else np.zeros((h, 0), bool)


def width(text, **kw):
    return render(text, **kw).shape[1]
