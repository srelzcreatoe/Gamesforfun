#!/usr/bin/env python3
"""Lists of vanilla block ids for the engine-side block queries (which take ids, not patterns).

The script decides what may be broken with patterns (src/havoc.ts: NEVER, STORAGE; src/world.ts: NATURAL).
Basiliskra IV clears whole volumes in one engine call, and that call can only be told which block *ids* to
leave alone.  This applies those same patterns to Mojang's block list for the game version and writes the
matches to src/generated/ids.ts, so the two can never disagree.

    python3 tools/kit/gen_ids.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SAMPLES = os.environ.get("BEDROCK_SAMPLES", "/home/user/mojang/bedrock-samples")


def pattern(path, name):
    src = open(os.path.join(ROOT, path)).read()
    m = re.search(r"const %s = /(.+)/;" % name, src)
    if not m:
        sys.exit(f"{path}: no pattern {name}")
    return re.compile(m.group(1))


def main():
    blocks = os.path.join(SAMPLES, "metadata", "vanilladata_modules", "mojang-blocks.json")
    out = os.path.join(ROOT, "src", "generated", "ids.ts")
    if not os.path.exists(blocks):
        if os.path.exists(out):
            print("gen_ids: Mojang's block list is not here; keeping the lists already generated")
            return
        sys.exit("gen_ids: Mojang's block list is needed (bedrock-samples/metadata/vanilladata_modules/mojang-blocks.json)")
    ids = sorted(b["name"] for b in json.load(open(blocks))["data_items"])
    never, storage, natural = pattern("src/havoc.ts", "NEVER"), pattern("src/havoc.ts", "STORAGE"), pattern("src/world.ts", "NATURAL")
    lists = {
        "NEVER_IDS": [i for i in ids if never.search(i)],
        "STORAGE_IDS": [i for i in ids if storage.search(i) and not never.search(i)],
        "NATURAL_IDS": [i for i in ids if natural.search(i) and "glazed" not in i],
    }
    ts = ["// GENERATED by tools/kit/gen_ids.py from the patterns in havoc.ts and world.ts and Mojang's block list.  Do not edit.", ""]
    for name, got in lists.items():
        ts.append(f"export const {name}: string[] = {json.dumps(got)};")
    with open(out, "w") as f:
        f.write("\n".join(ts) + "\n")
    print("block id lists: " + ", ".join(f"{len(v)} {k}" for k, v in lists.items()))


if __name__ == "__main__":
    main()
